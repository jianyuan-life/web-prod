// ── 單次生成主 prompt ──
export function buildSingleCallV6C(
  clientName: string,
  age: number,
  maritalStatus?: string,
  clientNeed?: string,
  kbRules?: string,
): string {
  const ageGroup = getV6AgeGroup(age)
  const kbSection = kbRules
    ? `\n【知識庫引據(從專家規則庫檢索、與此盤面直接相關;寫附錄「體系解讀」時優先引用這些條目的觀點與 KB 編號;缺的不補造)】\n${kbRules}\n`
    : ''
  const needSection = clientNeed
    ? `\n【客戶自述的關注(第四章「處境套用」須涵蓋)】${clientNeed}\n`
    : ''
  return `${v6CoreRules()}

${AGE_ADAPTATION[ageGroup]}

${maritalAdaptation(maritalStatus)}
${needSection}${kbSection}
【本次任務】為「${clientName}」寫完整的 v6 人生藍圖(人生手冊體)。依上方結構契約單次輸出全書。
- 原型稱號:從盤面提煉一個專屬稱號(格式「把…的人」或同等白話),開卷第一卡立、收卷回收
- 每個判斷先想「這句放在三層語氣的哪一層」;寫完自查:正文有沒有任何黑名單術語、有沒有絕對化、每章核對夠不夠三個
- 附錄判斷對照至少 18 條、每條與正文錨點對得上;正文每個「(出處見附錄 XX-nn)」在附錄必須存在`
}
