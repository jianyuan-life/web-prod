// ── 年齡層判定(v6 分層矩陣;<13 歲 = 家長版)──
export type V6AgeGroup = 'child_parent' | 'teen' | 'young' | 'establishing' | 'midlife' | 'senior'
export function getV6AgeGroup(age: number): V6AgeGroup {
  if (age < 13) return 'child_parent'
  if (age < 20) return 'teen'
  if (age < 28) return 'young'
  if (age < 45) return 'establishing'
  if (age < 60) return 'midlife'
  return 'senior'
}

